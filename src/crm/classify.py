"""
Простая классификация ответов продавца по ключевым словам.

Зачем без машинного обучения
----------------------------
Ответов на первом этапе десятки, и правила-ключевики прозрачны: всегда можно
посмотреть, почему ответ попал в категорию, поправить список слов и
пересчитать всё заново (`run_crm.py recategorize` — тексты хранятся целиком).
Когда ответов станут тысячи и правил перестанет хватать, поверх этого же
интерфейса можно подставить модель — вызывающий код не изменится.

Порядок правил важен: «НЕ интересно» должно попасть в негатив раньше, чем
«интересно» сработает как позитив.
"""

import re

from .store import (
    REPLY_INTERESTED,
    REPLY_NEGATIVE,
    REPLY_NEUTRAL,
    REPLY_OTHER,
    REPLY_POSITIVE,
    REPLY_NEEDS_INFO,
)

# Группы в порядке проверки. Регэкспы без привязки к регистру; «ё» пишем
# через [её], чтобы «ещё» и «еще» ловились одинаково.
_RULES = [
    (
        REPLY_NEGATIVE,
        [
            r"не\s+интересно",
            r"не\s+нужно",
            r"не\s+надо",
            r"не\s+надобност",
            r"не\s+актуальн",
            r"не\s+заинтересован",
            r"не\s+сотруднича",
            r"нам\s+не\s+подходит",
            r"не\s+планируем",
            r"не\s+будем",
            r"не\s+ищем",
            r"откаж",
            r"отписаться",
            r"не\s+беспоко",
            r"не\s+писать",
            r"спам",
        ],
    ),
    (
        REPLY_INTERESTED,
        [
            r"заинтересован",
            r"интересно",
            r"интересует",
            r"давай[йт]е\s+(обсудим|поговорим|свяж)",
            r"можно\s+обсудить",
            r"готов[ыа]?\s+(обсудить|сотрудничать|работать|посмотреть|услышать)",
            r"давайте\s+сотрудничать",
            r"жду\s+(предложение|предложения|условия|прайс)",
            r"хотим\s+(сотрудничать|работать|заказывать)",
            r"хотим\s+купить",
            r"давайте\s+начнем",
            r"нас\s+это\s+актуально",
        ],
    ),
    (
        REPLY_NEEDS_INFO,
        [
            r"расскажите",
            r"подробнее",
            r"больше\s+информации",
            r"поделитесь\s+информаци",
            r"что\s+за\s+(продукт|товар|условия|предложение)",
            r"какие\s+(условия|цены|товары)",
            r"сколько\s+(стоит|будет|примерно)",
            r"какая\s+цена",
            r"цены\s+в\s+личку",
            # «пришлите X» — просьба о материалах, это запрос информации,
            # а не готовность: прайс/условия/каталог живут здесь, не в позитиве
            r"пришлите\s+(прайс|условия|предложени[ея]|пример|каталог|ссылку|список)",
            r"скиньте\s+(прайс|каталог|условия)",
            r"напишите\s+(мне|в\s+личку|подробн)",
            r"уточните",
            r"есть\s+вопрос",
        ],
    ),
    (
        REPLY_POSITIVE,
        [
            r"спасибо",
            r"благодар",
            r"здорово",
            r"отлично",
            r"хорошего\s+дня",
            r"удачи",
            r"рад[ыа]?\s+сотрудничеству",
            r"всё\s+понятно",
            r"все\s+понятно",
        ],
    ),
    (
        REPLY_NEUTRAL,
        [
            r"^ок\b",
            r"^хорошо$",
            r"^понял",
            r"^ладно$",
            r"добрый\s+день",
            r"здравствуйте",
            r"привет",
            r"кто\s+это",
            r"вы\s+кто",
            r"о\s+чём\s+речь",
            r"о\s+чем\s+речь",
        ],
    ),
]

_COMPILED = [
    (category, [re.compile(pattern, re.IGNORECASE) for pattern in patterns])
    for category, patterns in _RULES
]


def classify_reply(text: str) -> str:
    """Категория ответа: одна из REPLY_*, ДРУГОЕ как запасной вариант.

    Пустой текст — ДРУГОЕ: это не «не ответил» (тот случай вообще не имеет
    входящего сообщения и не попадает сюда).
    """
    normalized = (text or "").strip()
    if not normalized:
        return REPLY_OTHER
    for category, patterns in _COMPILED:
        if any(pattern.search(normalized) for pattern in patterns):
            return category
    return REPLY_OTHER
